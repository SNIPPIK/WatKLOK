/// Коды операций голосового WebSocket-протокола Discord.
///
/// Значения соответствуют официальной документации Discord Voice Gateway.
///
/// # Структура op-кодов
///
/// Протокол не является «плоским»: коды разделены на два диапазона.
///
/// * `0..20` — базовая сигнализация: Identify, Select Protocol, Ready,
///   Heartbeat, Speaking, Resume, Hello, события о клиентах канала.
///   Эти коды существовали с первых версий протокола и не менялись.
///
/// * `21..31` — расширение DAVE (E2EE через MLS): управление переходами
///   между версиями, обмен MLS-сообщениями, подтверждения. Появилось
///   относительно недавно и активно развивается.
///
/// Разделение важно: код `21` — не «ещё один базовый op», а первый
/// в DAVE-диапазоне. Обработчики проверяют не только конкретный код,
/// но и диапазон (`is_dave`): если Discord добавит новый DAVE-код,
/// он попадёт в общем обработчике, даже если отдельная константа
/// для него ещё не заведена.
///
/// # Тип `u64`
///
/// Все константы — `u64`, потому что JSON-числа парсятся в `u64`.
/// Приведение к `u8` (или другому узкому типу) делается уже после
/// извлечения поля `op` из пакета — так избегаем ошибок с отрицательными
/// значениями и переполнением при невалидных данных от сервера.
pub mod discord_opcode {
    // ---------------------------------------------------------------------
    // Базовые op-коды (0..20)
    // ---------------------------------------------------------------------

    /// Идентификация клиента (регистрация голосового подключения).
    ///
    /// Первое сообщение после открытия WebSocket. Содержит `server_id`,
    /// `session_id`, `user_id`, `token` и `max_dave_protocol_version`.
    /// Без Identify сервер не знает, кто мы и куда хотим подключиться.
    pub const IDENTIFY: u64 = 0;

    /// Выбор транспортного протокола (UDP/TLS) после получения данных от шлюза.
    ///
    /// Отправляется после discovery: сообщает серверу, что мы готовы
    /// принимать медиа по UDP, и передаёт наш внешний адрес/порт
    /// (полученный в ответ на discovery-пакет).
    pub const SELECT_PROTOCOL: u64 = 1;

    /// Готовность голосового канала к работе.
    ///
    /// Приходит в ответ на Identify. Содержит `ssrc`, `ip`, `port` —
    /// данные для UDP discovery. После него начинается discovery.
    pub const READY: u64 = 2;

    /// Отправка heartbeat-пакета для поддержания соединения.
    ///
    /// Периодический пульс. Содержит `t` (время отправки) и `seq_ack`
    /// (последний полученный seq). Без heartbeat сервер через ~40
    /// разрывает соединение.
    pub const HEARTBEAT: u64 = 3;

    /// Описание сессии: SSRC, ключи шифрования, режим.
    ///
    /// Приходит после Select Protocol. Содержит `secret_key` для
    /// AEAD-шифрования RTP и (опционально) `dave_protocol_version`.
    /// После него транспорт готов к отправке/приёму аудио.
    pub const SESSION_DESCRIPTION: u64 = 4;

    /// Уведомление о состоянии говорящего (start/stop).
    ///
    /// Отправляется, когда бот начинает или заканчивает передачу.
    /// Содержит `speaking` (битовая маска), `delay`, `ssrc`.
    pub const SPEAKING: u64 = 5;

    /// Подтверждение полученного heartbeat.
    ///
    /// Приходит в ответ на Heartbeat. Если ACK не пришёл до следующего
    /// тика — считается пропущенным, и после нескольких пропусков
    /// соединение закрывается.
    pub const HEARTBEAT_ACK: u64 = 6;

    /// Возобновление сессии с сохранением seq.
    ///
    /// Отправляется после переподключения, если session_id тот же.
    /// Позволяет восстановить соединение без полного рукопожатия.
    pub const RESUME: u64 = 7;

    /// Приветствие от шлюза с интервалом heartbeat.
    ///
    /// Первое сообщение после открытия WebSocket. Содержит
    /// `heartbeat_interval` (в мс), по которому запускается пульс.
    pub const HELLO: u64 = 8;

    /// Подтверждение успешного возобновления сессии.
    ///
    /// Приходит в ответ на Resume. После него соединение считается
    /// восстановленным, и можно продолжать обмен как обычно.
    pub const RESUMED: u64 = 9;

    /// Уведомление о подключении новых клиентов к каналу.
    ///
    /// Содержит `user_ids` — список подключившихся. Нужно DAVE
    /// для построения дерева ключей MLS.
    pub const CLIENTS_CONNECT: u64 = 11;

    /// Уведомление об отключении клиента от канала.
    ///
    /// Содержит `user_id` — кто отключился. DAVE использует это,
    /// чтобы исключить его из дерева ключей.
    pub const CLIENT_DISCONNECT: u64 = 13;

    // ---------------------------------------------------------------------
    // DAVE (E2EE / MLS) — расширение Discord для сквозного шифрования
    // ---------------------------------------------------------------------
    //
    // Диапазон 21..31. Все коды в нём относятся к управлению E2EE:
    // переходами между версиями протокола, обменом MLS-сообщениями,
    // подтверждениями. Если Discord добавит новый DAVE-код — он попадёт
    // в тот же диапазон, и общий обработчик его подхватит.

    /// Подготовка к переходу между версиями протокола.
    ///
    /// Сервер предлагает новую версию. Если `transition_id != 0`,
    /// переход требует подтверждения от всех участников (см.
    /// `DAVE_TRANSITION_READY`). Если `== 0` — переход выполняется
    /// сразу, без обмена подтверждениями.
    pub const DAVE_PREPARE_TRANSITION: u64 = 21;

    /// Выполнение подготовленного перехода.
    ///
    /// Приходит после того, как все участники подтвердили готовность.
    /// Содержит `transition_id`, по которому сессия понимает,
    /// какой именно переход выполнять.
    pub const DAVE_EXECUTE_TRANSITION: u64 = 22;

    /// Подтверждение готовности к переходу от другой стороны.
    ///
    /// Отправляется в ответ на `DAVE_PREPARE_TRANSITION`, если переход
    /// требует подтверждения. Без него переход не завершится у всех
    /// участников.
    pub const DAVE_TRANSITION_READY: u64 = 23;

    /// Подготовка новой эпохи (инициализация E2EE-сессии).
    ///
    /// Только эпоха 1 запускает инициализацию MLS. Остальные эпохи —
    /// это ротация ключей внутри уже работающей сессии.
    pub const DAVE_PREPARE_EPOCH: u64 = 24;

    /// Внешний отправитель MLS-сессии.
    ///
    /// Бинарное сообщение. Содержит данные, необходимые MLS для проверки
    /// подписей. Приходит один раз, до proposals/commit.
    pub const DAVE_MLS_EXTERNAL_SENDER: u64 = 25;

    /// Key-package для распространения среди участников.
    ///
    /// Бинарное сообщение. Отправляется, когда сессия готова принять
    /// новых участников или после повторной инициализации. Другие участники
    /// используют его для добавления нас в MLS-группу.
    pub const DAVE_MLS_KEY_PACKAGE: u64 = 26;

    /// Предложения (Proposals) от других участников.
    ///
    /// Бинарное сообщение. Содержит предложения по изменению состава
    /// MLS-группы (добавить/удалить участника). В ответ нужно отправить
    /// commit (+ welcome).
    pub const DAVE_MLS_PROPOSALS: u64 = 27;

    /// Commit и Welcome MLS-сессии.
    ///
    /// Бинарное сообщение. Ответ на proposals: commit применяет
    /// изменения, welcome позволяет новому участнику присоединиться
    /// к группе. Первый байт — префикс-опкод, остальное — данные.
    pub const DAVE_MLS_COMMIT_WELCOME: u64 = 28;

    /// Анонс Commit-перехода.
    ///
    /// Бинарное сообщение. Приходит от другого участника, применившего
    /// commit. Мы должны применить его у себя и подтвердить переход.
    pub const DAVE_MLS_ANNOUNCE_COMMIT_TRANSITION: u64 = 29;

    /// Welcome-сообщение для присоединения к группе.
    ///
    /// Бинарное сообщение. Приходит новому участнику MLS-группы,
    /// чтобы он мог расшифровать сообщения остальных. После применения
    /// нужно подтвердить переход.
    pub const DAVE_MLS_WELCOME: u64 = 30;

    /// Уведомление о невалидности Commit или Welcome.
    ///
    /// Отправляется, если нативная сессия обнаружила, что commit/welcome
    /// невалиден. Сигнал другим участникам, что нужно повторной инициализации.
    pub const DAVE_MLS_INVALID_COMMIT_WELCOME: u64 = 31;

    /// Проверяет, относится ли op-код к диапазону DAVE.
    ///
    /// # Аргументы
    /// * `code` — op-код из полученного сообщения.
    ///
    /// # Возвращаемое значение
    /// `true`, если код принадлежит диапазону DAVE/MLS.
    ///
    /// # Зачем нужна проверка диапазоном
    ///
    /// Вместо перечисления всех кодов через `||` — проверка диапазона
    /// `[DAVE_PREPARE_TRANSITION, DAVE_MLS_INVALID_COMMIT_WELCOME]`.
    /// Это надёжнее: если Discord добавит новый DAVE-код (например, 32),
    /// мы просто расширим границу, и все DAVE-сообщения продолжат
    /// попадать общий обработчик. Перечисление через `||` потребовало
    /// бы добавить новую ветку, а забыть легко.
    #[inline]
    pub fn is_dave(code: u64) -> bool {
        code >= DAVE_PREPARE_TRANSITION
            && code <= DAVE_MLS_INVALID_COMMIT_WELCOME
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        // Проверяет границы диапазона DAVE: коды до 21 и после 31
        // не считаются DAVE, коды 21 и 31 — считаются.
        fn is_dave_boundaries() {
            assert!(!is_dave(0));
            assert!(!is_dave(DAVE_PREPARE_TRANSITION - 1));
            assert!(is_dave(DAVE_PREPARE_TRANSITION));
            assert!(is_dave(DAVE_MLS_INVALID_COMMIT_WELCOME));
            assert!(!is_dave(DAVE_MLS_INVALID_COMMIT_WELCOME + 1));
            assert!(!is_dave(255));
        }
    }
}

/// Статусы WebSocket-соединения.
///
/// Соответствуют стандартным состояниям `WebSocket.readyState` из браузера.
/// Используются в `VoiceWebSocket` для геттера `status`.
pub mod ws_status {
    /// Устанавливается соединение (handshake в процессе).
    pub const CONNECTING: u8 = 0;

    /// Соединение открыто и готово к обмену данными.
    pub const OPEN: u8 = 1;

    /// Соединение закрывается.
    pub const CLOSING: u8 = 2;

    /// Соединение закрыто.
    pub const CLOSED: u8 = 3;
}

/// Коды закрытия соединения, специфичные для Discord Voice.
///
/// # Структура кодов
///
/// * `1000` — стандартный WebSocket-код нормального закрытия.
///   Используется в `STOP_CODES`: если сервер закрывает соединение
///   с этим кодом, переподключаться бессмысленно.
///
/// * `4009..4022` — коды Discord Voice Gateway. Префикс `40` означает
///   «ошибка уровня приложения» (не WebSocket-протокола). Каждый код
///   соответствует конкретной проблеме, и вызывающий код может
///   различать их: например, `CALL_TERMINATED` — штатное завершение,
///   `SERVER_NOT_FOUND` — проблема с endpoint, `SESSION_TIMEOUT` —
///   пропущенный heartbeat.
pub mod close_codes {
    /// Нормальное закрытие WebSocket.
    ///
    /// Стандартный код протокола WebSocket (RFC 6455). Означает, что
    /// соединение закрыто штатно, без ошибок.
    pub const NORMAL: u32 = 1000;

    /// Session timeout (в т.ч. пропущенный HEARTBEAT_ACK).
    ///
    /// Сервер закрывает соединение, если не получил heartbeat-ACK
    /// вовремя. Это не проблема клиента по сути — просто пропуск,
    /// но переподключение потребуется.
    pub const SESSION_TIMEOUT: u32 = 4009;

    /// `VoiceCloseCodes::ServerNotFound`.
    ///
    /// Endpoint, к которому мы пытались подключиться, не существует
    /// или недоступен. Обычно означает, что данные VOICE_SERVER_UPDATE
    /// были неверными.
    pub const SERVER_NOT_FOUND: u32 = 4011;

    /// `VoiceCloseCodes::Disconnected`.
    ///
    /// Пользователь намеренно отключился от канала. Один из `STOP_CODES`:
    /// переподключаться не нужно.
    pub const DISCONNECTED: u32 = 4014;

    /// `VoiceCloseCodes::VoiceServerCrashed`.
    ///
    /// Голосовой сервер упал. Обычно означает, что стоит попробовать
    /// другое подключение — endpoint мог измениться.
    pub const VOICE_SERVER_CRASHED: u32 = 4015;

    /// `VoiceCloseCodes::BadRequest`.
    ///
    /// Некорректный запрос: обычно неверный Identify или Select Protocol.
    /// Переподключаться бессмысленно — ошибка не исправится сама.
    pub const BAD_REQUEST: u32 = 4020;

    /// `VoiceCloseCodes::CallTerminated`.
    ///
    /// Звонок завершён. Используется как код причины в `TransportEvent::Destroyed`,
    /// когда транспорт уничтожается штатно (не по ошибке).
    pub const CALL_TERMINATED: u32 = 4022;
}

/// Проверяет, относится ли op-код к диапазону DAVE.
///
/// Удобная функция-обёртка над [`discord_opcode::is_dave`] для использования
/// без явного указания модуля.
///
/// # Зачем дубль
///
/// `is_dave` живёт в `discord_opcode`, но при вызове из внешнего кода
/// пришлось бы писать `discord_opcode::is_dave(...)` — шумно, особенно
/// когда функция вызывается часто. Эта обёртка позволяет писать
/// `is_dave(...)` напрямую, а модуль остаётся точкой правды: реализация
/// ровно одна, дублирования логики нет.
#[inline]
pub fn is_dave(code: u64) -> bool {
    discord_opcode::is_dave(code)
}