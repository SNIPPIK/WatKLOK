//! Канал Rust -> JS. Одна threadsafe-функция, события в виде JSON-строк.
//!
//! События (поле `t`):
//! * `log`             — `{ src: "voice" | "transport", text }`;
//! * `send`            — `{ payload }` (готовый пакет для gateway-адаптера);
//! * `destroyed`       — `{ guild_id }` (удалить соединение из `db.voice`);
//! * `adapter_destroy` — вызвать `adapter.destroy()` (всегда последним).
//!
//! Один колбэк вместо нескольких — намеренно. napi-обёртка над каждой
//! threadsafe-функцией стоит денег (своя очередь, свой refcount), а событий
//! на горячем пути немного. Общий канал проще: JS-сторона разбирает JSON
//! по полю `t` и решает, что делать.
//!
//! JSON-строки, а не структуры — потому что между Rust и JS всё равно
//! нет общего типа: JS получает уже готовый объект (или строку, которую
//! разбирает `JSON.parse`). Строки дешевле передавать, чем строить
//! napi-объекты вручную.

use parking_lot::Mutex;
use serde_json::{json, Value};
use std::sync::Arc;

/// Событие, которое шина отправляет в JS.
///
/// Варианты различаются по смыслу и адресату:
/// * `Log` — диагностика, адресат — логгер JS;
/// * `Send` — пакет для gateway, адресат — gateway-адаптер;
/// * `Destroyed` — команда «удали соединение из БД»;
/// * `AdapterDestroy` — команда «уничтожь адаптер».
pub enum HostEvent {
    /// Лог. `transport` различает источник: транспорт или само подключение.
    Log { transport: bool, text: String },

    /// Готовый пакет для отправки через gateway-адаптер.
    Send(Value),

    /// Соединение уничтожено; `guild_id` — какое именно (если известен).
    /// `None` для личных сообщений: удалять из БД нечего.
    Destroyed(Option<String>),

    /// Адаптер уничтожен. **Всегда приходит последним**: после него
    /// `close()` освобождает колбэк, и других событий уже не будет.
    AdapterDestroy
}

/// Тип получателя событий — потокобезопасная функция, построенная
/// на стороне napi. Хранится в `Arc`, потому что вызывается из разных
/// потоков и может копироваться при отправке.
type Sink = Arc<dyn Fn(String) + Send + Sync>;

/// Шина событий Rust -> JS.
///
/// Живёт в `Arc`: на неё смотрят подключение, транспорт и обработчики
/// событий, каждое из которых может эмитить события.
pub struct HostBus {
    /// Получатель событий. `None`, пока JS не зарегистрировал колбэк,
    /// и после `close()`. `Mutex<Option<...>>` — потому что `set_sink`
    /// и `close` меняют его, а `emit` читает.
    sink: Mutex<Option<Sink>>
}

impl HostBus {
    /// Создаёт пустую шину без получателя.
    ///
    /// Возвращает `Arc`: шина сразу нужна нескольким владельцам,
    /// и передавать её по ссылке между ними было бы неудобно.
    pub fn new() -> Arc<Self> {
        Arc::new(Self { sink: Mutex::new(None) })
    }

    /// Устанавливает получателя событий (JS-колбэк).
    ///
    /// Может вызываться повторно: предыдущий получатель просто
    /// заменяется. Это полезно при переподключении, когда старый
    /// колбэк мог быть уничтожен вместе с адаптером.
    pub fn set_sink(&self, sink: Sink) {
        *self.sink.lock() = Some(sink);
    }

    /// Отправляет событие в JS.
    ///
    /// Если получатель не установлен — событие тихо теряется.
    /// Это осознанно: шина может использоваться до того, как JS-сторона
    /// успела подписаться, или после `close()`. Бросать ошибку в этом
    /// случае хуже — вызывающий код не должен зависеть от того,
    /// успел ли JS подписаться.
    pub fn emit(&self, event: HostEvent) {
        // Клонируем `Arc` под мьютексом, а вызываем без него.
        // Napi-вызов может быть дорогим или реентерабельным — держать
        // мьютекс на это время нельзя.
        let sink = self.sink.lock().clone();
        let Some(sink) = sink else { return };

        // Сериализуем в JSON сразу: каждый вариант знает свою форму,
        // и нам не нужно городить общий тип вроде `serde_json::Value`
        // на уровне API шины.
        let value = match event {
            HostEvent::Log { transport, text } => json!({
                "t": "log",

                // Строка вместо bool: JS-стороне проще разбирать
                // `src === "transport"`, чем проверять флаг
                // в отдельном поле рядом с текстом.
                "src": if transport { "transport" } else { "voice" },
                "text": text
            }),
            HostEvent::Send(payload) => json!({ "t": "send", "payload": payload }),

            // `guild_id` передаётся как есть: `None` превращается
            // в `null` в JSON, что JS-сторона понимает.
            HostEvent::Destroyed(guild_id) => json!({ "t": "destroyed", "guild_id": guild_id }),
            HostEvent::AdapterDestroy => json!({ "t": "adapter_destroy" }),
        };

        // Отправляем через napi-колбэк. Ошибки самого колбэка
        // здесь не обрабатываются: если JS-сторона упала, это
        // уже не наша забота.
        sink(value.to_string());
    }

    /// Удобная обёртка для логирования.
    ///
    /// `impl Into<String>` — чтобы можно было передавать и `&str`,
    /// и `String`, без ручного `.to_string()` на каждом вызове.
    pub fn log(&self, transport: bool, text: impl Into<String>) {
        self.emit(HostEvent::Log { transport, text: text.into() });
    }

    /// Освобождает JS-колбэк (после `adapter_destroy`).
    ///
    /// После вызова все последующие `emit` будут тихо терять события —
    /// это правильно, потому что адаптер уже уничтожен и обрабатывать
    /// события некому. Сам колбэк (threadsafe-функция) освобождается
    /// здесь, чтобы не держать napi-объект до сборки мусора.
    pub fn close(&self) {
        *self.sink.lock() = None;
    }
}