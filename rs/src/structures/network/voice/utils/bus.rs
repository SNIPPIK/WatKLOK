use parking_lot::Mutex;
use serde_json::{json, Value};
use std::sync::Arc;

/// Событие, которое шина отправляет в JS.
///
/// Варианты различаются по смыслу и адресату:
/// * `Log` — диагностика, адресат — логгер JS;
/// * `Send` — пакет для gateway, адресат — gateway-адаптер;
/// * `Destroyed` — команда «удали соединение из БД»;
/// * `AdapterDestroy` — команда «уничтожь адаптер».
pub enum HostEvent {
    /// Лог. `transport` различает источник: транспорт или само подключение.
    ///
    /// Разделение на два источника нужно потому, что JS-сторона
    /// обрабатывает их по-разному: логи подключения идут через
    /// событие `info` (`VoiceConnection`), а логи транспорта —
    /// напрямую в `Logger`. Так плагины и UI могут подписаться
    /// на `info`, не получая шума от низкоуровневых сообщений.
    Log { transport: bool, text: String },

    /// Готовый пакет для отправки через gateway-адаптер.
    ///
    /// Rust формирует пакет (например, `VoiceStateUpdate` при
    /// `set_status(Connecting)` или `disconnect`) и передаёт его
    /// на JS-сторону, где `adapter.send(payload)` отправляет его
    /// в gateway.
    ///
    /// `Value`, а не `String` — потому что payload уже структурирован
    /// на стороне Rust (через `json!`), и сериализовать его второй раз
    /// нет смысла: JS-сторона получит объект через `JSON.parse` той же
    /// строки, что и весь пакет.
    Send(Value),

    /// Соединение уничтожено; `None` для личных сообщений.
    ///
    /// `Some(guild_id)` — JS-сторона удаляет соединение из `db.voice`.
    /// `None` — соединение было в личных сообщениях, удалять из БД
    /// нечего.
    Destroyed(Option<String>),

    /// Адаптер уничтожен. **Всегда приходит последним**: после него
    /// колбэк освобождается, и других событий уже не будет.
    ///
    /// Это контракт: `emit` для этого варианта **забирает** `sink`
    /// из `Option`, а не клонирует. Все последующие `emit` увидят
    /// `None` и тихо потеряют событие — что правильно, потому что
    /// адаптер уже мёртв.
    AdapterDestroy
}

/// Тип получателя событий — потокобезопасная функция, построенная на стороне napi.
///
/// `Arc<dyn Fn(String) + Send + Sync>` — потому что шина хранит получателя
/// и вызывает его из разных потоков. `String` — уже готовая JSON-строка,
/// которую JS-сторона разберёт через `JSON.parse`.
type Sink = Arc<dyn Fn(String) + Send + Sync>;

/// Шина событий Rust -> JS.
///
/// Живёт в `Arc`: на неё смотрят подключение, транспорт и обработчики
/// событий, каждое из которых может эмитить события.
pub struct HostBus {
    /// Получатель событий. `None` до регистрации и после `close()`.
    ///
    /// `Mutex<Option<...>>` — потому что `set_sink` и `close` меняют его,
    /// а `emit` читает (и иногда забирает). `parking_lot::Mutex` —
    /// быстрее стандартного и без отравления.
    sink: Mutex<Option<Sink>>,

    /// Сериализует вызовы sink, чтобы порядок событий был строгим.
    ///
    /// Берётся ДО `sink`; порядок локов везде один: `order` -> `sink`.
    /// Это гарантирует, что события приходят в том порядке, в котором
    /// их эмитили, даже если `emit` вызывается из разных потоков
    /// одновременно.
    ///
    /// Без этого лока два потока могли бы одновременно взять `sink`
    /// (клон), а затем вызвать его в произвольном порядке — и события
    /// пришли бы в JS не по порядку. Для `log` это было бы терпимо,
    /// но для `send` и `destroyed` — нет: `adapter_destroy` должен
    /// прийти строго последним, а `send` — в исходном порядке.
    ///
    /// `()` — лок-мьютекс, защищает сам факт «я внутри emit».
    /// Данные не нужны: важно только сериализовать доступ.
    order: Mutex<()>
}

impl HostBus {
    /// Создаёт пустую шину без получателя.
    ///
    /// Возвращает `Arc`: шина сразу нужна нескольким владельцам
    /// (подключение, транспорт, обработчики), и передавать её
    /// по ссылке между ними было бы неудобно.
    pub fn new() -> Arc<Self> {
        Arc::new(Self {
            sink: Mutex::new(None),
            order: Mutex::new(())
        })
    }

    /// Устанавливает получателя событий (JS-колбэк). Предыдущий заменяется.
    ///
    /// Может вызываться повторно — например, при переподключении, когда
    /// старый колбэк мог быть уничтожен вместе с адаптером. Новый
    /// колбэк заменяет старый, не дожидаясь `close`.
    ///
    /// Лок `order` берётся, чтобы не пересечься с `emit`: иначе `set_sink`
    /// мог бы поменять получателя в середине `emit` (между проверкой
    /// `has_sink` и фактическим вызовом), и событие ушло бы не тому
    /// получателю.
    pub fn set_sink(&self, sink: Sink) {
        let _order = self.order.lock();
        *self.sink.lock() = Some(sink);
    }

    /// `true`, если получатель установлен.
    ///
    /// Позволяет не аллоцировать строки для событий, которые всё равно
    /// будут потеряны. На горячем пути (`log` в цикле) это заметно:
    /// `format!` строки — дороже, чем проверка `Option::is_some`.
    ///
    /// Лок `order` здесь НЕ берётся: проверка «есть ли sink» — не критичная
    /// операция, и брать `order` ради неё значило бы сериализовать
    /// все проверки между собой. `sink.lock()` достаточно: мы либо видим
    /// актуальное значение, либо (в худшем случае) слегка устаревшее —
    /// это приемлемо для проверки «стоит ли вообще пытаться».
    pub fn has_sink(&self) -> bool {
        self.sink.lock().is_some()
    }

    /// Отправляет событие в JS.
    ///
    /// Если получатель не установлен — событие тихо теряется.
    /// Это осознанно: шина может использоваться до того, как JS-сторона
    /// успела подписаться, или после `close()`. Бросать ошибку в этом
    /// случае хуже — вызывающий код не должен зависеть от того,
    /// успел ли JS подписаться.
    pub fn emit(&self, event: HostEvent) {
        // Дешёвый выход до сериализации. Если sink нет — не тратим
        // время на `json!` и `to_string`.
        if !self.has_sink() { return; }

        // `last` = это последнее событие. Нужно, чтобы `adapter_destroy`
        // забрал sink из `Option`, а не клонировал его: после
        // `adapter_destroy` никаких событий быть не должно.
        let last = matches!(event, HostEvent::AdapterDestroy);

        // Сериализуем в JSON сразу: каждый вариант знает свою форму,
        // и нам не нужно городить общий тип вроде `serde_json::Value`
        // на уровне API шины.
        let value = match event {
            HostEvent::Log { transport, text } => json!({
                "t": "log",

                // Строка вместо bool: JS-стороне проще разбирать
                // `src === "transport"`, чем проверять флаг
                // в отдельном поле рядом с текстом.
                "src": if transport { "transport" } else { "voice" },
                "text": text
            }),
            HostEvent::Send(payload) => json!({ "t": "send", "payload": payload }),

            // `guild_id` передаётся как есть: `None` превращается
            // в `null` в JSON, что JS-сторона понимает.
            HostEvent::Destroyed(guild_id) => json!({ "t": "destroyed", "guild_id": guild_id }),
            HostEvent::AdapterDestroy => json!({ "t": "adapter_destroy" }),
        };
        let text = value.to_string();

        // Весь вызов sink идёт под `order`: события уходят строго по очереди.
        // Лок берётся ПОСЛЕ сериализации: сериализация не зависит
        // от получателя и может идти параллельно у разных потоков.
        let _order = self.order.lock();
        let sink = if last {
            // `adapter_destroy` забирает sink: все последующие `emit`
            // увидят `None` и тихо потеряют событие. Это гарантирует,
            // что после последнего события ничего не уйдёт.
            self.sink.lock().take()
        } else {
            // Обычное событие: клонируем `Arc`, чтобы отпустить лок
            // `sink` до вызова. `sink(text)` может быть долгим
            // (napi-вызов), и держать `sink.lock()` на это время —
            // значит блокировать других, кто тоже хочет эмитить.
            self.sink.lock().clone()
        };

        if let Some(sink) = sink {
            // Ошибки колбэка не обрабатываем: если JS упал, это не наша забота.
            // `NonBlocking` в napi-обёртке уже гарантирует, что вызов
            // не блокирует Rust-поток.
            sink(text);
        }
    }

    /// Удобная обёртка для логирования.
    ///
    /// Строка не аллоцируется, если получателя нет. `text: impl Into<String>`
    /// позволяет передавать и `&str`, и `String` без ручного `.to_string()`.
    ///
    /// Проверка `has_sink()` здесь важна: `text.into()` может быть
    /// дорогим (если передан `String` с большим содержимым), и делать
    /// его ради события, которое всё равно потеряется, — расточительно.
    pub fn log(&self, transport: bool, text: impl Into<String>) {
        if !self.has_sink() { return; }
        self.emit(HostEvent::Log { transport, text: text.into() });
    }

    /// Освобождает JS-колбэк (после `adapter_destroy`). Идемпотентно.
    ///
    /// После вызова все последующие `emit` будут тихо терять события —
    /// это правильно, потому что адаптер уже уничтожен и обрабатывать
    /// события некому. Сам колбэк (threadsafe-функция) освобождается
    /// здесь, чтобы не держать napi-объект до сборки мусора.
    ///
    /// Лок `order` берётся, чтобы не пересечься с `emit`: если `emit`
    /// сейчас в процессе, `close` подождёт его завершения. Иначе
    /// `close` мог бы освободить sink, пока `emit` ещё держит клон
    /// `Arc`, — и колбэк был бы уничтожен до вызова.
    pub fn close(&self) {
        let _order = self.order.lock();
        *self.sink.lock() = None;
    }
}