//! Параметры планировщика отправки.

use crate::utils::duration::FRAME_DURATION_MS;
use std::time::Duration;

/// Нижняя граница (и стартовое значение) запаса, на который воркер
/// «недосыпает» до дедлайна и добирает остаток спином.
///
/// `thread::sleep` просыпается с опозданием (timer slack, загрузка CPU,
/// планировщик ОС). Спин на последнем отрезке гасит этот разброс ценой
/// части ядра на активный воркер. Реальный запас подстраивается под
/// измеренное опоздание сна (см. `SpinMargin`) в пределах
/// `SPIN_MARGIN..=SPIN_MARGIN_MAX`.
pub const SPIN_MARGIN: Duration = Duration::from_micros(250);

/// Верхняя граница адаптивного запаса сна: 2 мс — 10% кадра, дальше спин
/// стоит дороже, чем разовый выброс задержки.
pub const SPIN_MARGIN_MAX: Duration = Duration::from_millis(2);

/// Скорость «забывания» запаса: каждый сон возвращает 1/2^N разницы между
/// текущим запасом и нужным. Растёт запас мгновенно, снижается медленно.
pub const SPIN_MARGIN_DECAY_SHIFT: u32 = 4;

/// Максимальное отставание, которое воркер догоняет подряд идущими тиками
/// (5 кадров). Дальше дедлайн пересинхронизируется: после долгой паузы
/// (остановка процесса, перегруз хоста) пакеты не отправляются залпом.
pub const MAX_CATCHUP: Duration = Duration::from_millis(100);

/// Сколько после последнего пакета сессия считается «в потоке», мкс.
///
/// Пока хоть одна сессия воркера в потоке, воркер сохраняет ритм (короткий
/// провал очереди не сбивает дедлайны). Когда все сессии вне потока, воркер
/// засыпает на условной переменной и не просыпается каждые 20 мс.
pub const STREAM_GRACE_US: u64 = 100_000;

/// Как часто воркер проверяет keepalive сессий.
pub const KEEPALIVE_SWEEP: Duration = Duration::from_secs(1);

/// Порог перегрузки воркера: 20% кадра.
///
/// Пакеты сессий воркера уходят подряд после дедлайна, поэтому стоимость
/// тика — это максимальный разброс момента отправки между сессиями одного
/// воркера. Порог держит этот разброс на уровне единиц миллисекунд (далеко
/// от джиттер-буфера получателя); при превышении сессии выносятся на
/// другой воркер.
pub const OVERLOAD_THRESHOLD_NS: u64 = FRAME_DURATION_MS * 1_000_000 / 5;

/// Сколько тиков подряд воркер должен быть перегружен, чтобы вынести сессию.
pub const OVERLOAD_TICKS: u32 = 2;

/// Оценка стоимости одной сессии на тике, нс. Нужна балансировщику, пока
/// реальные измерения нового воркера ещё не накопились.
pub const SESSION_COST_ESTIMATE_NS: u64 = 20_000;

/// Жёсткий предел сессий на воркер (страховка от неверных оценок).
pub const MAX_SESSIONS_PER_WORKER: usize = 512;

/// Вес нового измерения в скользящем среднем: 1/2^N.
pub const EMA_SHIFT: u32 = 4;
