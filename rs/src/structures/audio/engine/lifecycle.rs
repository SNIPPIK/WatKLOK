//! Уничтожение движка и `Drop`.

use super::AudioEngine;
use napi::bindgen_prelude::*;
use napi_derive::napi;
use std::sync::atomic::Ordering;

#[napi]
impl AudioEngine {
    /// Уничтожает движок.
    ///
    /// Идемпотентный и потокобезопасный:
    /// если другой поток уже выполняет уничтожение, текущий вызов
    /// дождётся его завершения.
    #[napi]
    pub fn destroy(&self) -> Result<()> {
        self.force_destroy();
        Ok(())
    }

    /// Будит reader на обоих condvar без риска потерянного пробуждения.
    ///
    /// Reader проверяет флаги остановки, УДЕРЖИВАЯ соответствующий мьютекс,
    /// и сразу после проверки засыпает на `wait()` (мьютекс отпускается
    /// атомарно). Если вызвать `notify_all()` без мьютекса, возможна гонка:
    /// reader увидел `false`, мы выставили флаги и «покричали» в пустоту,
    /// reader заснул навсегда — `join()` в `destroy()` зависает.
    ///
    /// Короткий захват-отпускание мьютекса перед `notify_all()` гарантирует,
    /// что reader либо уже спит (получит notify), либо проверит флаги
    /// после нас и увидит новые значения.
    ///
    /// Флаги обязаны быть выставлены ДО вызова.
    pub(crate) fn wake_reader(&self) {
        drop(self.buffer.0.lock().unwrap_or_else(|p| p.into_inner()));
        self.buffer.1.notify_all();

        drop(self.pause_state.0.lock().unwrap_or_else(|p| p.into_inner()));
        self.pause_state.1.notify_all();
    }

    /// Принудительно уничтожает движок.
    ///
    /// Порядок:
    ///
    /// 1. Сериализует destroy-операции.
    /// 2. Атомарно переводит движок в состояние destroyed.
    /// 3. Останавливает reader.
    /// 4. Будит reader на condvar.
    /// 5. Забирает FFmpeg и завершает его.
    /// 6. Дожидается reader thread.
    /// 7. Очищает и освобождает audio buffer.
    pub fn force_destroy(&self) {
        // ------------------------------------------------------------------
        // Сериализация уничтожения.
        //
        // Конкурентный destroy не должен просто выйти сразу:
        // он должен дождаться полного завершения первого.
        // ------------------------------------------------------------------
        let _destroy_guard = self
            .destroy_lock
            .lock()
            .unwrap_or_else(|p| p.into_inner());

        // ------------------------------------------------------------------
        // Идемпотентность.
        //
        // Первый destroy выполняет cleanup.
        // Последующие после ожидания mutex просто выходят.
        // ------------------------------------------------------------------
        if self.destroyed.swap(true, Ordering::AcqRel) {
            return;
        }

        // ------------------------------------------------------------------
        // Останавливаем reader.
        //
        // Используется Release, чтобы изменения состояния были опубликованы
        // reader thread.
        // ------------------------------------------------------------------
        self.reading_active
            .store(false, Ordering::Release);

        // ------------------------------------------------------------------
        // БУДИМ reader СРАЗУ.
        //
        // Он может находиться:
        //   - на pause condvar;
        //   - на buffer condvar.
        //
        // Не имеет смысла ждать FFmpeg, прежде чем разбудить thread:
        // reader уже получил reading_active = false и должен завершиться.
        // ------------------------------------------------------------------
        self.wake_reader();

        // ------------------------------------------------------------------
        // Забираем Child из Mutex.
        //
        // Важно: wait() выполняется ПОСЛЕ освобождения child mutex.
        // Иначе другие операции, которым нужен self.child, могут зависнуть
        // на всём времени ожидания процесса.
        // ------------------------------------------------------------------
        let process = {
            let mut child = self
                .child
                .lock()
                .unwrap_or_else(|p| p.into_inner());

            child.take()
        };

        if let Some(mut process) = process {
            // Если FFmpeg ещё жив — завершаем его.
            //
            // Ошибка kill здесь не является фатальной:
            // процесс мог завершиться между try_wait() и kill().
            if process.try_wait().ok().flatten().is_none() {
                let _ = process.kill();
            }

            // Reap процесса.
            //
            // Это важно, чтобы не оставлять zombie process.
            let _ = process.wait();
        }

        // ------------------------------------------------------------------
        // Забираем JoinHandle отдельно от mutex.
        //
        // Не держим reader_handle mutex во время join().
        // ------------------------------------------------------------------
        let join_handle = {
            let mut handle = self
                .reader_handle
                .lock()
                .unwrap_or_else(|p| p.into_inner());

            handle.take()
        };

        // ------------------------------------------------------------------
        // Ожидаем полного завершения reader.
        // ------------------------------------------------------------------
        if let Some(join) = join_handle {
            let _ = join.join();
        }

        // ------------------------------------------------------------------
        // Теперь reader гарантированно больше не использует buffer.
        // Можно безопасно очищать его.
        // ------------------------------------------------------------------
        {
            let mut buffer = self
                .buffer
                .0
                .lock()
                .unwrap_or_else(|p| p.into_inner());

            buffer.clear();
        }
    }
}

/// Гарантированное освобождение ресурсов при удалении объекта.
impl Drop for AudioEngine {
    fn drop(&mut self) {
        self.force_destroy();
    }
}