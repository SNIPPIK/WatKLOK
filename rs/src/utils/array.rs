use std::collections::HashSet;

/// Множество с сохранением порядка и удалением через `swap-remove`.
#[derive(Default)]
pub struct SetArray {
    /// Элементы в порядке добавления (или в том, что остался после
    /// `swap-remove`). Именно этот массив отдаётся наружу через `array()`.
    array: Vec<String>,

    /// Индекс для быстрой проверки существования.
    /// Содержит те же строки, что и `array`, но без порядка.
    set: HashSet<String>,
}

impl SetArray {
    /// Добавляет элемент; дубликаты игнорируются.
    ///
    /// Проверка идёт по `set`, поэтому O(1). Если элемент уже есть,
    /// ничего не делаем: и `array`, и `set` остаются как были.
    pub fn add(&mut self, item: String) {
        // Дубликат — выходим. Проверка по `set`, а не по `array`:
        // `Vec::contains` был бы O(N) на каждое добавление.
        if self.set.contains(&item) {
            return;
        }

        // Клонируем строку: `set` и `array` владеют каждая своей копией.
        // Без клона пришлось бы использовать `Rc<str>` или индексы,
        // но для десятков элементов это лишнее усложнение.
        self.set.insert(item.clone());
        self.array.push(item);
    }

    /// Удаляет элемент через `swap-remove`. `true`, если элемент был.
    ///
    /// Порядок нарушается: на место удалённого встаёт последний элемент.
    /// Это сделано намеренно — так удаление из `Vec` остаётся O(1),
    /// а не O(N) со сдвигом хвоста. Для списка участников канала
    /// порядок неважен, поэтому такой компромисс оправдан.
    pub fn delete(&mut self, item: &str) -> bool {
        // Быстрый отсев: если элемента нет в `set`, нет смысла искать
        // его в `array`. Проверка O(1) вместо O(N).
        if !self.set.contains(item) {
            return false;
        }

        // Поиск индекса в `array` всё равно O(N): `HashSet` не хранит
        // позиции. Если когда-нибудь это станет узким местом, можно
        // завести `HashMap<String, usize>` и обновлять индексы при
        // `swap-remove` — но это уже другая структура данных.
        if let Some(index) = self.array.iter().position(|x| x == item) {
            let last = self.array.len() - 1;
            // JS: array[index] = array[last]; array.pop()
            // Если элемент уже последний, swap не нужен — сразу pop.
            if index != last {
                self.array.swap(index, last);
            }
            self.array.pop();
        }

        // Удаляем из `set` после `array`: если бы сделали наоборот
        // и что-то пошло не так в `array`, `set` уже не содержал бы
        // элемент, и повторный `delete` вернул бы false.
        self.set.remove(item);
        true
    }

    /// Элементы в текущем порядке.
    ///
    /// Возвращает срез, а не копию: вызывающий может пройтись по нему
    /// без выделения памяти. Если нужна копия — `.to_vec()`.
    pub fn array(&self) -> &[String] {
        &self.array
    }
}