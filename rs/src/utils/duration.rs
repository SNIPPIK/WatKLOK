/// Монотонное время в миллисекундах с момента первого вызова.
///
/// Не зависит от перевода системных часов, NTP-скачков и т.п. —
/// в отличие от `SystemTime::now()`, который может прыгнуть назад
/// или вперёд, `Instant` гарантирует монотонность.
///
/// # Точка отсчёта
///
/// `START` инициализируется при первом вызове и больше не меняется.
/// Значит, первый вызов вернёт ~0, а все последующие — время,
/// прошедшее с первого вызова. Это удобно для измерения интервалов
/// внутри процесса, но **не** для абсолютных меток времени:
/// значение `mono_ms()` в разных запусках процесса несравнимо.
pub fn mono_ms() -> u64 {
    use std::sync::OnceLock;
    use std::time::Instant;

    // `START` — точка отсчёта. `OnceLock` гарантирует, что
    // `Instant::now()` выполнится ровно один раз, даже если
    // несколько потоков вызовут `mono_ms()` одновременно.
    //
    // `Instant::now()` в `get_or_init` — ленивая инициализация:
    // до первого вызова `START` пуст, и мы не тратим время
    // на создание `Instant` при старте программы.
    static START: OnceLock<Instant> = OnceLock::new();

    // `elapsed()` возвращает `Duration` от `START` до текущего момента.
    // `as_millis()` — миллисекунды как `u128`; приведение к `u64`
    // безопасно на практике (см. doc).
    START.get_or_init(Instant::now).elapsed().as_millis() as u64
}